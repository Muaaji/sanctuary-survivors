'use strict';
const assert=require('node:assert/strict');
const {createContext,buildReport,markdown}=require('../scripts/report-stats.cjs');
const c=createContext(),S=c.SurvivorStats,R=c.SurvivorRuntime,C=c.SurvivorCatalogue;
const close=(a,b)=>assert.ok(Math.abs(a-b)<1e-9,`${a} != ${b}`);
const stats=(id,level=1,evolved=false)=>R.stats({id,level,evolved});
const report=buildReport();
assert.equal(report.profiles.length,7);assert.equal(report.rows.length,270);
for(const row of report.rows)for(const field of ['damage','cd','count','radius','duration','crit','critDamage','mana','allyHP'])assert.ok(Number.isFinite(row[field]),`${row.id} ${row.rank} ${field}`);
assert.equal(markdown(report).split('\n').filter(s=>s.startsWith('| common_')).length,60);
c.Player.classId='sorceress';
const fire=stats('sorceress_fireball');c.Player.passives.ranged=1;
close(stats('sorceress_fireball').dmg-fire.dmg,C.spells.sorceress_fireball.dmg*.08);
c.Player.passives={attackSpeed:5};close(stats('sorceress_fireball').cd,fire.cd);
c.Player.classId='druid';c.Player.passives={};const wolf=stats('druid_wolves');
c.Player.passives={attackSpeed:5};close(stats('druid_wolves').cd,wolf.cd/1.3);
assert.equal(S.activation(wolf),'passive');assert.equal(S.manaCost(wolf),0);
c.Player.passives={area:5};close(stats('druid_wolves').radius,wolf.radius*1.2);
c.Player.passives={};close(stats('druid_wolves',5).allyHP,70*1.84);
close(stats('druid_wolves',5,true).allyHP,stats('druid_wolves',5).allyHP*1.5);
assert.equal(stats('druid_wolves',5).count,C.spells.druid_wolves.count+2);
c.Player.passives={cooldown:5};const a=S.get();close(a.cdr,.2);
c.Player.passives={crit:100,critDamage:1,dodge:100,cooldown:100};
assert.equal(S.get().crit,.75);assert.equal(S.get().dodge,.45);assert.equal(S.get().cdr,.5);close(S.get().critDamage,2.02);
c.Player.passives={};c.Player.classId='sorceress';
for(const [rank,L] of [[1,1],[2,2.75],[3,4.5],[4,6.25],[5,8]])close(stats('sorceress_fireball',rank).level,L);
const before=stats('sorceress_fireball',5),after=stats('sorceress_fireball',5,true);
close(after.dmg,before.dmg*1.5);close(after.cd,before.cd*.8);
assert.equal(S.manaCost(after),Math.round(Math.min(22,7+after.cd*1.5)));
assert.equal(S.manaDrain(C.spells.druid_hurricane),6);assert.equal(S.manaDrain(C.spells.paladin_holyfire),4);
console.log('PASS stats foundations: 270 finite rows, category, speed, zone, rank, caps, mana and companions');
